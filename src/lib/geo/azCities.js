function normalizeCityKey(raw) {
  return String(raw || "")
    .toLowerCase()
    .replace(/ə/g, "ə")
    .replace(/ı/g, "ı")
    .replace(/ö/g, "ö")
    .replace(/ü/g, "ü")
    .replace(/ğ/g, "ğ")
    .replace(/ş/g, "ş")
    .replace(/ç/g, "ç")
    .trim();
}

function hashJitter(seed) {
  const s = String(seed || "0");
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  const a = ((h % 1000) / 1000 - 0.5) * 0.06;
  const b = (((h >> 10) % 1000) / 1000 - 0.5) * 0.06;
  return [a, b];
}

/**
 * @param {string} city
 * @param {string} [seed] — registryNo / id для разброса
 * @returns {{ lat: number, lng: number, precision: "city"|"unknown" } | null}
 */
export function coordsForCity(city, seed = "") {
  const key = normalizeCityKey(city);
  if (!key) return null;

  let hit = AZ_CITY_COORDS[key];
  if (!hit) {
    // частичное совпадение: «Bakı şəhəri», «Abşeron rayonu»
    for (const [name, coords] of Object.entries(AZ_CITY_COORDS)) {
      if (key.includes(name) || name.includes(key.split(/\s+/)[0])) {
        hit = coords;
        break;
      }
    }
  }
  if (!hit) return null;

  const [jLat, jLng] = hashJitter(seed);
  return {
    lat: Math.round((hit[0] + jLat) * 1e5) / 1e5,
    lng: Math.round((hit[1] + jLng) * 1e5) / 1e5,
    precision: "city",
  };
}

/** Если lat/lng пустые или мусор — подставить по городу */
export function ensureLotCoords(lot) {
  if (!lot) return lot;
  const latOk = Number.isFinite(Number(lot.lat)) && Math.abs(Number(lot.lat)) > 0.01;
  const lngOk = Number.isFinite(Number(lot.lng)) && Math.abs(Number(lot.lng)) > 0.01;
  if (latOk && lngOk) {
    return {
      ...lot,
      lat: Number(lot.lat),
      lng: Number(lot.lng),
    };
  }
  const city = lot.cityAz || lot.cityRu || lot.districtAz || lot.districtRu || "";
  const c = coordsForCity(city, lot.registryNo || lot.id);
  if (!c) {
    // fallback: Bakı с jitter — лот всё равно виден на карте
    const [jLat, jLng] = hashJitter(lot.registryNo || lot.id || "x");
    return {
      ...lot,
      lat: Math.round((40.4093 + jLat) * 1e5) / 1e5,
      lng: Math.round((49.8671 + jLng) * 1e5) / 1e5,
      geoPrecision: "fallback_baku",
    };
  }
  return { ...lot, lat: c.lat, lng: c.lng, geoPrecision: c.precision };
}
